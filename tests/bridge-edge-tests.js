// Optional second selftest input after shim.js; never evaluate in the game.
(function () {
  'use strict';
  const check=(v,label)=>{if(!v)throw new Error('Bridge edge test: '+label);};
  const throws=(f,label)=>{let failed=false;try{f();}catch(e){failed=true;}check(failed,label);};
  const p=Memory.alloc(128);
  p.writeU8(255).add(1).writeU16(65535).add(3).writeU32(0xffffffff);
  check(p.readU8()===255&&p.add(1).readU16()===65535&&p.add(4).readU32()===0xffffffff,'unaligned unsigned widths');
  p.add(16).writeU64(uint64('18446744073709551615'));
  check(p.add(16).readU64().toString()==='18446744073709551615','full unsigned range');
  check(uint64(-1).equals('18446744073709551615'),'unsigned wrapping');
  check(ptr('0xffffffffffffffff').toInt32()===-1,'pointer signed low bits');
  check(ptr('0xffffffffffffffff').toUInt32()===0xffffffff,'pointer unsigned low bits');
  check(p.add(8).sub(8).equals(p),'pointer arithmetic');
  const array=new Uint8Array([99,12,34,56,88]);
  p.add(32).writeByteArray(array.subarray(1,4));
  check(Array.from(new Uint8Array(p.add(32).readByteArray(3))).join(',')==='12,34,56','typed-array byte offset');
  p.add(36).writeByteArray(new Uint16Array([0x1234]));
  check(p.add(36).readU16()===0x1234,'typed-array byte size');
  p.add(40).writeByteArray([2,3,4]);
  check(p.add(42).readU8()===4,'plain byte array');
  p.writeByteArray(new Uint8Array(0));
  check(p.readByteArray(0).byteLength===0,'empty byte arrays');
  check(ptr(0).readCString()===null&&ptr(0).readUtf16String()===null&&ptr(0).readByteArray(1)===null,'null string/byte reads');
  const wide=Memory.allocUtf16String('Привет 🐟');
  check(wide.readUtf16String()==='Привет 🐟','null-terminated UTF16');
  check(wide.readUtf16String(3)==='При','bounded UTF16');
  check(wide.readUtf16String(0)==='','empty UTF16');
  check(Memory.allocUtf16String('\ud800').readUtf16String(1)==='\ud800','UTF16 code-unit preservation');
  const utf8=Memory.allocUtf8String('Привет 🐟');
  check(utf8.readCString()==='Привет 🐟','UTF8');
  check(Memory.allocUtf8String('abc\0def').readCString(7)==='abc','embedded terminator');
  check(JSON.stringify({p:ptr(16),u:uint64('18446744073709551615')})==='{"p":"0x10","u":"18446744073709551615"}','JSON exactness');
  const length=new NativeFunction(Module.getExportByName('kernel32.dll','lstrlenW'),'uint32',['pointer']);
  check(length(wide)===9,'one-argument native dispatch');
  const compare=new NativeFunction(Module.getExportByName('kernel32.dll','lstrcmpW'),'uint32',['pointer','pointer']);
  check(compare(wide,wide)===0,'two-argument native dispatch');
  throws(()=>ptr(1).readDouble(),'SEH scalar read');
  throws(()=>ptr(1).writeU32(1),'SEH scalar write');
  throws(()=>ptr(1).readCString(4),'SEH string read');
  throws(()=>ptr(1).readByteArray(4),'SEH byte read');
  throws(()=>ptr(1).writeByteArray([1]),'SEH byte write');
  throws(()=>new NativeFunction(ptr(1),'uint32',[])(),'SEH indirect call');
  throws(()=>ptr(Number.MAX_SAFE_INTEGER+1),'reject imprecise addresses');
  throws(()=>Memory.alloc(-1),'negative allocation');
  throws(()=>Memory.alloc(67108865),'allocation limit');
  throws(()=>new NativeFunction(ptr(1),'double',[]),'reject floating ABI');
  throws(()=>new NativeFunction(ptr(1),'void',['pointer','pointer','pointer','pointer']),'reject >3 arguments');
  throws(()=>length(),'native argument count');
  throws(()=>Module.getExportByName('kernel32.dll','__not_a_real_export__'),'missing export');
})();
