function uiBeforeDraw() {
  uiUpdateLayout();
  if (!config.open) {
    uiState.drag = null;
    uiState.regions = [];
    uiState.pendingChars = [];
    uiState.pendingWheel = 0;
    uiState.mouseValid = false;
    return;
  }
  if (typeof focused === 'function' && !focused()) {
    uiState.drag = null;
    uiState.pendingChars = [];
    uiState.pendingWheel = 0;
    uiState.mouseValid = false;
    key(1);
    return;
  }
  if (uiState.inputActive) uiHideNativeHUD();
  uiState.mouseValid = false;
  try {
    const uiMouse = call(pc, 'PlayerController', 'GetMousePosition');
    if (uiMouse.add(8).readU8()) {
      uiState.mouseX = (uiMouse.readFloat() * uiState.mouseScaleX - uiState.x) / uiState.scale;
      uiState.mouseY = (uiMouse.add(4).readFloat() * uiState.mouseScaleY - uiState.y) / uiState.scale;
      uiState.mouseValid = Number.isFinite(uiState.mouseX) && Number.isFinite(uiState.mouseY);
    }
  } catch (_) {}
  const uiWasDragging = !!uiState.drag;
  if (uiState.drag) {
    if ((keyState(1) & 0x8000) !== 0 && uiState.mouseValid) uiRun(uiDragUpdate);
    else uiState.drag = null;
  }
  if (uiState.searchFocused) {
    let uiQuery = uiState.query;
    for (const uiCode of uiState.pendingChars) {
      if (uiCode === 8) {
        if (uiState.selectAllSearch) uiQuery = '';
        else { const uiChars = Array.from(uiQuery); uiChars.pop(); uiQuery = uiChars.join(''); }
        uiState.selectAllSearch = false;
      } else if (uiCode >= 32 && uiCode !== 127) {
        if (uiState.selectAllSearch) uiQuery = '';
        uiState.selectAllSearch = false;
        if (uiQuery.length < 80) uiQuery += String.fromCharCode(uiCode);
      }
    }
    uiSetQuery(uiQuery);
  }
  uiState.pendingChars = [];
  if (config.tab === 1 && uiInside(0, 0, 1100, 850)) {
    uiState.wheelRemainder += uiState.pendingWheel;
    const uiSteps = Math.trunc(uiState.wheelRemainder / 120);
    if (uiSteps) {
      uiScroll(-uiSteps * 3);
      uiState.wheelRemainder -= uiSteps * 120;
    }
  }
  uiState.pendingWheel = 0;
  if (key(1) && uiState.mouseValid && !uiWasDragging) {
    let uiHit = null;
    for (let uiIndex = uiState.regions.length - 1; uiIndex >= 0; uiIndex--) {
      const uiCandidate = uiState.regions[uiIndex];
      if (uiInside(uiCandidate.x, uiCandidate.y, uiCandidate.w, uiCandidate.h)) { uiHit = uiCandidate; break; }
    }
    if (!uiHit || !uiHit.keepSearch) {
      uiState.searchFocused = false;
      uiState.selectAllSearch = false;
    }
    if (uiHit) uiRun(() => uiHit.action(uiState.mouseX, uiState.mouseY));
  }
}

function uiKeyboard() {
  if (!config.open || (typeof focused === 'function' && !focused())) return;
  const uiKeys = {};
  for (const uiVK of [0x76, 0x26, 0x28, 0x25, 0x27, 0x0d, 0x20, 0x21, 0x22, 0x24, 0x23, 0x09, 0x1b, 0x41, 0x46]) uiKeys[uiVK] = key(uiVK);
  if (uiKeys[0x76]) { uiSwitchTab((config.tab + 1) % 4); return; }
  if (config.tab === 3) {
    const uiFunControls = uiFunJob() ? [5, 1, 0, 6, 7, 2, 3, 4] : [5, 1, 0, 6, 7, 2, 3];
    let uiFunFocus = Math.max(0, uiFunControls.indexOf(uiState.navFun));
    if (uiKeys[0x26]) uiFunFocus = (uiFunFocus + uiFunControls.length - 1) % uiFunControls.length;
    if (uiKeys[0x28] || uiKeys[0x09]) uiFunFocus = (uiFunFocus + 1) % uiFunControls.length;
    uiState.navFun = uiFunControls[uiFunFocus];
    if (uiState.navFun === 1) {
      if (uiKeys[0x25]) uiSetMonsterScale(uiMonsterScale() - 1);
      if (uiKeys[0x27]) uiSetMonsterScale(uiMonsterScale() + 1);
      if (uiKeys[0x24]) uiSetMonsterScale(2);
      if (uiKeys[0x23]) uiSetMonsterScale(20);
    }
    if (uiState.navFun === 5) {
      if (uiKeys[0x25]) uiCycleFunFish(-1);
      if (uiKeys[0x27]) uiCycleFunFish(1);
    }
    if (uiState.navFun === 7) {
      if (uiKeys[0x25]) uiSetRainCount(uiRainCount() - 1);
      if (uiKeys[0x27]) uiSetRainCount(uiRainCount() + 1);
      if (uiKeys[0x24]) uiSetRainCount(1);
      if (uiKeys[0x23]) uiSetRainCount(100);
    }
    if (uiKeys[0x0d] || uiKeys[0x20]) uiRun(() => uiActivateFun(uiState.navFun));
    return;
  }
  if (config.tab === 2) {
    if (uiKeys[0x26]) uiState.navSettings = (uiState.navSettings + 3) % 4;
    if (uiKeys[0x28] || uiKeys[0x09]) uiState.navSettings = (uiState.navSettings + 1) % 4;
    if (uiState.navSettings === 3) {
      if (uiKeys[0x25]) setFeature('lang', 'ru');
      if (uiKeys[0x27]) setFeature('lang', 'en');
    }
    if (uiState.navSettings === 1) {
      if (uiKeys[0x25]) uiSetNoclipSpeed(uiNoclipSpeed() - 0.1);
      if (uiKeys[0x27]) uiSetNoclipSpeed(uiNoclipSpeed() + 0.1);
      if (uiKeys[0x24]) uiSetNoclipSpeed(0.5);
      if (uiKeys[0x23]) uiSetNoclipSpeed(10);
    }
    if (uiKeys[0x0d] || uiKeys[0x20]) {
      if (uiState.navSettings === 0) setFeature('noclip', config.noclip === false);
      if (uiState.navSettings === 2) uiSetNoclipSpeed(1.5);
      if (uiState.navSettings === 3) setFeature('lang', config.lang === 'en' ? 'ru' : 'en');
    }
    return;
  }
  if (config.tab === 0) {
    if (uiKeys[0x26]) uiState.navMod = (uiState.navMod + CATALOG.fish.length + 8) % (CATALOG.fish.length + 9);
    if (uiKeys[0x28] || uiKeys[0x09]) uiState.navMod = (uiState.navMod + 1) % (CATALOG.fish.length + 9);
    if (uiKeys[0x25]) uiRun(() => uiActivateMod(uiState.navMod, -1));
    if (uiKeys[0x27]) uiRun(() => uiActivateMod(uiState.navMod, 1));
    if (uiKeys[0x0d] || uiKeys[0x20]) uiRun(() => uiActivateMod(uiState.navMod, 0));
    return;
  }
  const uiCtrl = (keyState(0x11) & 0x8000) !== 0;
  if (uiCtrl && uiKeys[0x46]) {
    uiState.searchFocused = true;
    uiState.keyboardArea = 'search';
    uiState.selectAllSearch = true;
    return;
  }
  if (uiState.searchFocused) {
    if (uiCtrl && uiKeys[0x41]) uiState.selectAllSearch = true;
    if (uiKeys[0x0d] || uiKeys[0x1b] || uiKeys[0x09]) {
      uiState.searchFocused = false;
      uiState.selectAllSearch = false;
      uiState.keyboardArea = uiKeys[0x09] ? 'filters' : 'items';
    }
    return;
  }
  if (uiKeys[0x09]) {
    uiState.keyboardArea = uiState.keyboardArea === 'filters' ? 'items' : 'search';
    if (uiState.keyboardArea === 'search') uiState.searchFocused = true;
    return;
  }
  if (uiKeys[0x25]) uiState.keyboardArea = 'filters';
  if (uiKeys[0x27]) uiState.keyboardArea = 'items';
  if (uiKeys[0x21]) uiScroll(-uiState.visibleRows);
  if (uiKeys[0x22]) uiScroll(uiState.visibleRows);
  if (uiState.keyboardArea === 'filters') {
    const uiFilterCount = CATALOG.categories.length + 1;
    if (uiKeys[0x26]) uiState.filterIndex = (uiState.filterIndex + uiFilterCount - 1) % uiFilterCount;
    if (uiKeys[0x28]) uiState.filterIndex = (uiState.filterIndex + 1) % uiFilterCount;
    if (uiKeys[0x0d] || uiKeys[0x20]) {
      if (uiState.filterIndex === CATALOG.categories.length) setFeature('spawn', !config.spawn);
      else uiToggleFilter(CATALOG.categories[uiState.filterIndex].id);
    }
  } else {
    if (uiKeys[0x26]) uiSelectItem(uiState.selected - 1);
    if (uiKeys[0x28]) uiSelectItem(uiState.selected + 1);
    if (uiKeys[0x24]) uiSelectItem(0);
    if (uiKeys[0x23]) uiSelectItem(uiFilteredItems().length - 1);
    if (uiKeys[0x0d] || uiKeys[0x20]) {
      const uiEntry = uiFilteredItems()[uiState.selected];
      if (uiEntry) uiRun(() => issue(uiEntry.id));
    }
  }
}

