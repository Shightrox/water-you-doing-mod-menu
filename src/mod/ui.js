function uiControllerMode(uiController, uiMode) {
  call(defaults.WidgetBlueprintLibrary, 'WidgetBlueprintLibrary', uiMode, uiParams => {
    uiParams.writePointer(uiController);
    if (uiMode === 'SetInputMode_GameOnly') {
      uiParams.add(8).writeU8(1);
    } else {
      uiParams.add(8).writePointer(ptr(0));
      uiParams.add(16).writeU8(0);
      uiParams.add(17).writeU8(uiMode === 'SetInputMode_UIOnlyEx' ? 1 : 0);
      if (uiMode === 'SetInputMode_GameAndUIEx') uiParams.add(18).writeU8(1);
    }
  });
}

function uiHideNativeHUD() {
  if (!valid(pc)) return;
  for (const uiOffset of [2152, 2160]) {
    const uiWidget = pc.add(uiOffset).readPointer();
    if (!valid(uiWidget)) continue;
    const uiToken = uiWidget.toString() + ':' + uiWidget.add(12).readU32() + ':' + uiWidget.add(28).readU32();
    if (uiState.nativeHUDs.has(uiToken)) continue;
    const uiOpacity = call(uiWidget, 'Widget', 'GetRenderOpacity').readFloat();
    uiState.nativeHUDs.set(uiToken, { p: uiWidget, index: uiWidget.add(12).readU32(), number: uiWidget.add(28).readU32(), opacity: uiOpacity });
    call(uiWidget, 'Widget', 'SetRenderOpacity', uiParams => uiParams.writeFloat(0));
  }
}
function uiRestoreNativeHUD() {
  for (const uiSaved of uiState.nativeHUDs.values()) {
    if (!valid(uiSaved.p) || uiSaved.p.add(12).readU32() !== uiSaved.index || uiSaved.p.add(28).readU32() !== uiSaved.number) continue;
    try { call(uiSaved.p, 'Widget', 'SetRenderOpacity', uiParams => uiParams.writeFloat(uiSaved.opacity)); } catch (_) {}
  }
  uiState.nativeHUDs.clear();
}
function uiReleaseController() {
  uiRestoreNativeHUD();
  const uiController = uiState.capturePC;
  const uiCanRestore = uiController && valid(uiController) && uiController.add(12).readU32() === uiState.captureIndex;
  try {
    if (uiCanRestore) {
      try {
        uiControllerMode(uiController, uiState.savedCursor ? 'SetInputMode_GameAndUIEx' : 'SetInputMode_GameOnly');
      } finally {
        const uiCursorByte = uiController.add(1364);
        uiCursorByte.writeU8((uiCursorByte.readU8() & ~1) | (uiState.savedCursor ? 1 : 0));
      }
    }
  } finally {
    uiState.capturePC = null;
    uiState.captureIndex = -1;
    uiState.inputActive = false;
  }
}

function uiSetOpen(uiOn) {
  if (!uiOn) {
    uiState.drag = null;
    uiState.regions = [];
    uiState.searchFocused = false;
    uiState.selectAllSearch = false;
    uiState.pendingChars = [];
    uiState.pendingWheel = 0;
    uiState.wheelRemainder = 0;
    uiReleaseController();
    return true;
  }
  if (!valid(pc)) return false;
  if (uiState.inputActive && uiState.capturePC && uiState.capturePC.equals(pc) && pc.add(12).readU32() === uiState.captureIndex) return true;
  if (uiState.capturePC) uiReleaseController();
  uiState.capturePC = pc;
  uiState.captureIndex = pc.add(12).readU32();
  uiState.savedCursor = (pc.add(1364).readU8() & 1) !== 0;
  try {
    uiControllerMode(pc, 'SetInputMode_UIOnlyEx');
    pc.add(1364).writeU8(pc.add(1364).readU8() | 1);
    uiState.inputActive = true;
    uiHideNativeHUD();
    uiState.regions = [];
    uiState.pendingChars = [];
    uiState.pendingWheel = 0;
    uiState.mouseValid = false;
    // A mouse button already held while opening must not activate a control.
    key(1);
    return true;
  } catch (uiError) {
    try { uiReleaseController(); } catch (_) {}
    notify(tr('Не удалось включить управление меню мышью'));
    return false;
  }
}

function uiUpdateLayout() {
  try {
    const uiCanvas = hudNow.add(768).readPointer();
    if (!uiCanvas.isNull()) {
      const uiWidth = uiCanvas.add(0x40).readS32(), uiHeight = uiCanvas.add(0x44).readS32();
      if (uiWidth > 100 && uiWidth < 20000 && uiHeight > 100 && uiHeight < 20000) {
        uiState.canvasW = uiWidth;
        uiState.canvasH = uiHeight;
      }
    }
  } catch (_) {}
  uiState.scale = Math.min(1, Math.max(0.25, (uiState.canvasW - 40) / 1100), Math.max(0.25, (uiState.canvasH - 40) / 850));
  uiState.x = (uiState.canvasW - 1100 * uiState.scale) / 2;
  uiState.y = (uiState.canvasH - 850 * uiState.scale) / 2;
}

